// Generate September 2026 Attendance Records for realistic demonstration
export function generateInitialAttendance(): AttendanceRecord[] {
  const records: AttendanceRecord[] = [];
  const daysInSept = 30;

  INITIAL_EMPLOYEES.forEach((emp) => {
    for (let day = 1; day <= daysInSept; day++) {
      const dateStr = `2026-09-${String(day).padStart(2, '0')}`;
      const dayOfWeek = new Date(2026, 8, day).getDay(); // 0 is Sunday

      let status: 'PRESENT' | 'ABSENT' | 'HALF_DAY' | 'PAID_LEAVE' | 'UNPAID_LEAVE' | 'HOLIDAY' = 'PRESENT';
      let hours = 8;

      if (dayOfWeek === 0) {
        // Sunday is standard paid weekly off/holiday in construction
        status = 'HOLIDAY';
        hours = 0;
      } else if (emp.id === 'EMP-101' && (day === 8 || day === 22)) {
        status = 'PAID_LEAVE';
        hours = 0;
      } else if (emp.id === 'EMP-102' && day === 14) {
        status = 'HALF_DAY';
        hours = 4;
      } else if (emp.id === 'EMP-102' && day === 18) {
        status = 'ABSENT';
        hours = 0;
      } else if (emp.id === 'EMP-104' && day === 9) {
        status = 'HALF_DAY';
        hours = 4;
      }

      records.push({
        id: `ATT-${emp.id}-${dateStr}`,
        employeeId: emp.id,
        date: dateStr,
        status,
        hoursWorked: hours,
        recordedBy: 'Site Bio-Metric & Admin Sync',
        remarks: status === 'HALF_DAY' ? 'Heavy rain afternoon' : undefined,
      });
    }
  });

  return records;
}

